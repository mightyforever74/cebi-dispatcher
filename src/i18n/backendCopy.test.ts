/**
 * P1-3a — dispatcher alert title/description localization (locked, written
 * before implementation per WORKING_RULES.md "Mimari Bağlam Zorunluluğu").
 *
 * Core (`server.js`, task-start transaction — `PUT /api/driver/tasks/:id/start`)
 * inserts a hardcoded Turkish `alerts.title`/`description`:
 *   title       = "Görev Başladı"
 *   description = "Görev başladı: " + task_no
 * DashboardNavbar's bell-icon dropdown (`src/examples/Navbars/DashboardNavbar/
 * index.tsx:263`) and `useNotifications`' toast path both call
 * `localizeBackendAlert(raw, t)` (this file) and fall back to the RAW backend
 * string whenever it isn't recognized — which is exactly the reported bug
 * (TODO_ACTIVE.md §4: "Bildirim başlıkları EN arayüzde Türkçe ('Görev
 * Başladı')"). `localizeBackendAlert` already solves this for ONE other
 * backend string ("Görev kabul edildi:" -> notify.taskAccepted); this locks
 * the SAME pattern extended to the task-started alert:
 *
 *   1. The exact title "Görev Başladı" maps through the dictionary.
 *   2. The "Görev başladı: <detail>" description maps through the
 *      dictionary, carrying <detail> (the task_no) into the result.
 *   3. The pre-existing "Görev kabul edildi:" mapping is unaffected
 *      (no regression).
 *   4. Any unrecognized backend string still passes through unchanged.
 *   5. en/nl/tr dictionaries actually define both new keys end-to-end
 *      (not just a mapping function with nothing behind it).
 *
 * Do not edit this file to make it pass. Edit src/i18n/backendCopy.ts and
 * src/i18n/{en,nl,tr}.ts.
 *
 * Run (Windows): npm test -- backendCopy --watchAll=false
 */
import { localizeBackendAlert } from "./backendCopy";
import { en } from "./en";
import { nl } from "./nl";
import { tr } from "./tr";
import type { TranslationKey, TVars } from "./types";

// Flattens a nested dictionary module the same way src/i18n/index.ts does,
// without touching that module's mutable `currentLang` singleton — this
// test exercises the pure localizeBackendAlert(raw, translate) contract in
// isolation, across all three real dictionaries.
function flatten(node: unknown, prefix = "", out = new Map<string, string>()): Map<string, string> {
  if (typeof node === "string") {
    if (prefix) out.set(prefix, node);
    return out;
  }
  if (node && typeof node === "object") {
    Object.entries(node as Record<string, unknown>).forEach(([key, value]) => {
      flatten(value, prefix ? `${prefix}.${key}` : key, out);
    });
  }
  return out;
}

const DICTS = { en: flatten(en), nl: flatten(nl), tr: flatten(tr) } as const;

function interpolate(template: string, vars?: TVars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    vars[name] === undefined ? match : String(vars[name])
  );
}

function makeT(lang: keyof typeof DICTS) {
  return (key: TranslationKey, vars?: TVars): string => {
    const template = DICTS[lang].get(key);
    if (template === undefined) return key; // mirrors real t()'s missing-key fallback
    return interpolate(template, vars);
  };
}

test("maps the exact backend title 'Görev Başladı' through the dictionary (en)", () => {
  const result = localizeBackendAlert("Görev Başladı", makeT("en"));
  expect(result).not.toBe("Görev Başladı");
  expect(result.toLowerCase()).toContain("task");
  expect(result.toLowerCase()).toContain("start");
});

test("maps the exact backend title through the dictionary (nl)", () => {
  const result = localizeBackendAlert("Görev Başladı", makeT("nl"));
  expect(result).not.toBe("Görev Başladı");
  expect(result.toLowerCase()).toContain("taak");
});

test("Turkish dispatchers see the same text the backend already sends (no regression)", () => {
  const result = localizeBackendAlert("Görev Başladı", makeT("tr"));
  expect(result).toBe("Görev Başladı");
});

test("maps the 'Görev başladı: <detail>' description and carries the task_no through (en)", () => {
  const result = localizeBackendAlert("Görev başladı: TLP-26-00099", makeT("en"));
  expect(result).not.toContain("Görev");
  expect(result).toContain("TLP-26-00099");
});

test("maps the description through the dictionary (nl)", () => {
  const result = localizeBackendAlert("Görev başladı: TLP-26-00099", makeT("nl"));
  expect(result).not.toContain("Görev");
  expect(result).toContain("TLP-26-00099");
});

test("the pre-existing 'Görev kabul edildi:' mapping still works (no regression)", () => {
  const result = localizeBackendAlert("Görev kabul edildi: TLP-26-00042", makeT("en"));
  expect(result).toBe("Task accepted: TLP-26-00042");
});

test("an unrecognized backend string passes through unchanged", () => {
  const result = localizeBackendAlert("Tamamen alakasız bir metin", makeT("en"));
  expect(result).toBe("Tamamen alakasız bir metin");
});

test("undefined/empty input returns an empty string (matches existing contract)", () => {
  expect(localizeBackendAlert(undefined, makeT("en"))).toBe("");
  expect(localizeBackendAlert("", makeT("en"))).toBe("");
});

test("en/nl/tr dictionaries actually define the new keys (not just the mapping function)", () => {
  expect(DICTS.en.get("notify.taskStarted")).toBeDefined();
  expect(DICTS.nl.get("notify.taskStarted")).toBeDefined();
  expect(DICTS.tr.get("notify.taskStarted")).toBeDefined();
  expect(DICTS.en.get("notify.taskStartedDetail")).toContain("{detail}");
  expect(DICTS.nl.get("notify.taskStartedDetail")).toContain("{detail}");
  expect(DICTS.tr.get("notify.taskStartedDetail")).toContain("{detail}");
});
