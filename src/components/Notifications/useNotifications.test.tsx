import "@testing-library/jest-dom";
import { act, render, screen } from "@testing-library/react";
import { NotificationsProvider, useNotifications } from "./useNotifications";

const mockAckMutateAsync = jest.fn().mockResolvedValue({});
const mockResolveMutateAsync = jest.fn().mockResolvedValue({});
const mockExceptionResolve = jest.fn().mockResolvedValue({});

let mockAlerts: Array<{
  id: string;
  alert_type: string;
  severity: string;
  is_resolved: boolean;
  acknowledged_at: string | null;
  created_at: string;
}> = [];

jest.mock("store/useAuthStore", () => ({
  useAuthStore: (selector: (s: { token: string }) => unknown) => selector({ token: "test-token" }),
}));

jest.mock("hooks/useExceptions", () => ({
  useExceptions: () => ({
    exceptions: [],
    loading: false,
    error: null,
    newIds: new Set(),
    refresh: jest.fn(),
    resolve: mockExceptionResolve,
    lastOkAt: null,
  }),
}));

jest.mock("hooks/useAlerts", () => ({
  EMPTY_ALERTS: [],
  useAlerts: () => ({ data: mockAlerts }),
  useResolveAlert: () => ({ mutateAsync: mockResolveMutateAsync }),
  useAckAlert: () => ({ mutateAsync: mockAckMutateAsync }),
}));

function TestConsumer({
  onReady,
}: {
  onReady: (api: ReturnType<typeof useNotifications>) => void;
}) {
  const api = useNotifications();
  onReady(api);
  return (
    <div>
      {api.banners.map((b) => (
        <div key={b.id} data-testid={`banner-${b.id}`}>
          {b.title}
        </div>
      ))}
    </div>
  );
}

beforeEach(() => {
  window.localStorage.clear();
  mockAckMutateAsync.mockClear();
  mockResolveMutateAsync.mockClear();
  mockAlerts = [];
});

test("alert with acknowledged_at set is excluded from banners (server is source of truth)", () => {
  mockAlerts = [
    {
      id: "a1",
      alert_type: "sos",
      severity: "critical",
      is_resolved: false,
      acknowledged_at: null,
      created_at: new Date().toISOString(),
    },
    {
      id: "a2",
      alert_type: "driver_offline",
      severity: "critical",
      is_resolved: false,
      acknowledged_at: "2026-10-10T10:00:00.000Z",
      created_at: new Date().toISOString(),
    },
  ];

  render(
    <NotificationsProvider>
      <TestConsumer onReady={() => {}} />
    </NotificationsProvider>
  );

  expect(screen.getByTestId("banner-banner:sos")).toBeInTheDocument();
  expect(screen.queryByTestId("banner-banner:driver_offline")).not.toBeInTheDocument();
});

test("acknowledge() calls ackAlert for alert ids, never resolveAlert", async () => {
  mockAlerts = [
    {
      id: "a3",
      alert_type: "sos",
      severity: "critical",
      is_resolved: false,
      acknowledged_at: null,
      created_at: new Date().toISOString(),
    },
  ];

  let apiRef: ReturnType<typeof useNotifications> | null = null;

  render(
    <NotificationsProvider>
      <TestConsumer onReady={(api) => (apiRef = api)} />
    </NotificationsProvider>
  );

  const banner = apiRef!.banners.find((b) => b.id === "banner:sos");
  expect(banner).toBeDefined();

  await act(async () => {
    await apiRef!.acknowledge(banner!);
  });

  expect(mockAckMutateAsync).toHaveBeenCalledWith({ id: "a3" });
  expect(mockResolveMutateAsync).not.toHaveBeenCalled();
});
