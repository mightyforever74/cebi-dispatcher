/**
 * FEAT-020 Phase 1.3b (Katman C, dispatcher dilimi, 2026-10-13, Cem onayli).
 * Spec: docs/functions/FEAT-020-capacity-aware-delivery-promising.md §6.
 *
 * resolveCargoCapacity: tek bir arac satirindan (enterprise-backend
 * /api/dispatcher/vehicles, FN-3 kapandi) hangi kapasite kaynaginin
 * (statik mi canli mi) cargoScorer'a besleneceginin KARARINI verir.
 * cargoScorer.ts'in kendisi DEGISMEDI — bu dosya sadece veri-birlestirme
 * katmani, scorer'in kendisi hangi kaynaktan geldigini bilmiyor/bilmemeli.
 *
 * Kurallar (Cem onayli, spec §6):
 *  1. cargo_capacity_tracking === 'off' -> canli veri HER ZAMAN yok sayilir,
 *     statik veriye donulur (sirket bu feature'i hic istemiyor).
 *  2. 'required'/'optional' (veya alan hic gelmemisse — eski API yaniti,
 *     fail-open) + surucu en az bir kez rapor etmis (live_cargo_reported_at
 *     set) -> canli veri statigin ONUNE gecer.
 *  3. Hazmat sertifikasi HER ZAMAN statik kalir — surucu canli olarak
 *     sertifika bildirmiyor (spec §6 not 2).
 *  4. Hic statik hic canli veri yoksa -> undefined (Katman A'nin graceful
 *     degradation fallback'i degismedi, cargoScorer kendi icinde halleder).
 *  5. Canli rapor var ama sadece bir alan dolu (partial report) -> diger
 *     alan null doner, hayali statik deger KARISTIRILMAZ (canli rapor
 *     geldiyse tamamen canliya gecilir, karma kaynak YOK).
 *
 * Do not edit this file to make it pass. Edit cargoCapacityResolver.ts
 * (yeni dosya).
 */
import { resolveCargoCapacity, VehicleCargoRow } from "./cargoCapacityResolver";

function row(overrides: Partial<VehicleCargoRow>): VehicleCargoRow {
  return {
    cargo_capacity_volume_m3: undefined,
    cargo_capacity_weight_kg: undefined,
    hazmat_certified_classes: undefined,
    live_cargo_volume_m3: undefined,
    live_cargo_weight_kg: undefined,
    live_cargo_reported_at: undefined,
    cargo_capacity_tracking: undefined,
    ...overrides,
  };
}

describe("resolveCargoCapacity (FEAT-020 Katman C)", () => {
  test("hic statik hic canli veri yok -> undefined", () => {
    expect(resolveCargoCapacity(row({}))).toBeUndefined();
  });

  test("sadece statik veri var, canli hic rapor edilmemis -> statik kullanilir", () => {
    const result = resolveCargoCapacity(
      row({
        cargo_capacity_volume_m3: 40,
        cargo_capacity_weight_kg: 8000,
        hazmat_certified_classes: ["Sinif 3"],
      })
    );
    expect(result).toEqual({ volumeM3: 40, weightKg: 8000, hazmatCertifiedClasses: ["Sinif 3"] });
  });

  test("canli rapor var + tracking 'optional' -> canli statigin onune gecer", () => {
    const result = resolveCargoCapacity(
      row({
        cargo_capacity_volume_m3: 40,
        cargo_capacity_weight_kg: 8000,
        hazmat_certified_classes: ["Sinif 3"],
        live_cargo_volume_m3: 12,
        live_cargo_weight_kg: 1500,
        live_cargo_reported_at: "2026-10-13T10:00:00Z",
        cargo_capacity_tracking: "optional",
      })
    );
    expect(result).toEqual({ volumeM3: 12, weightKg: 1500, hazmatCertifiedClasses: ["Sinif 3"] });
  });

  test("canli rapor var + tracking 'required' -> canli statigin onune gecer", () => {
    const result = resolveCargoCapacity(
      row({
        live_cargo_volume_m3: 5,
        live_cargo_weight_kg: 200,
        live_cargo_reported_at: "2026-10-13T10:00:00Z",
        cargo_capacity_tracking: "required",
      })
    );
    expect(result).toEqual({ volumeM3: 5, weightKg: 200, hazmatCertifiedClasses: [] });
  });

  test("canli rapor var ama tracking 'off' -> canli YOK SAYILIR, statige donulur", () => {
    const result = resolveCargoCapacity(
      row({
        cargo_capacity_volume_m3: 40,
        cargo_capacity_weight_kg: 8000,
        live_cargo_volume_m3: 12,
        live_cargo_weight_kg: 1500,
        live_cargo_reported_at: "2026-10-13T10:00:00Z",
        cargo_capacity_tracking: "off",
      })
    );
    expect(result).toEqual({ volumeM3: 40, weightKg: 8000, hazmatCertifiedClasses: [] });
  });

  test("tracking 'off' + sadece canli veri var (statik hic yok) -> undefined (canli yok sayildi, statik de yok)", () => {
    const result = resolveCargoCapacity(
      row({
        live_cargo_volume_m3: 12,
        live_cargo_weight_kg: 1500,
        live_cargo_reported_at: "2026-10-13T10:00:00Z",
        cargo_capacity_tracking: "off",
      })
    );
    expect(result).toBeUndefined();
  });

  test("tracking alani hic gelmemis (eski API yaniti / join basarisiz) -> fail-open, canli veri yine kullanilir", () => {
    const result = resolveCargoCapacity(
      row({
        live_cargo_volume_m3: 7,
        live_cargo_weight_kg: 300,
        live_cargo_reported_at: "2026-10-13T10:00:00Z",
        cargo_capacity_tracking: undefined,
      })
    );
    expect(result).toEqual({ volumeM3: 7, weightKg: 300, hazmatCertifiedClasses: [] });
  });

  test("canli rapor edilmis ama sadece hacim gonderilmis (partial) -> agirlik null, statikten KARISTIRILMAZ", () => {
    const result = resolveCargoCapacity(
      row({
        cargo_capacity_volume_m3: 40,
        cargo_capacity_weight_kg: 8000,
        live_cargo_volume_m3: 12,
        live_cargo_weight_kg: null,
        live_cargo_reported_at: "2026-10-13T10:00:00Z",
        cargo_capacity_tracking: "optional",
      })
    );
    expect(result).toEqual({ volumeM3: 12, weightKg: null, hazmatCertifiedClasses: [] });
  });

  test("hazmat her zaman statikten gelir, canli rapor hazmat'i etkilemez", () => {
    const result = resolveCargoCapacity(
      row({
        hazmat_certified_classes: ["Sinif 8"],
        live_cargo_volume_m3: 12,
        live_cargo_weight_kg: 1500,
        live_cargo_reported_at: "2026-10-13T10:00:00Z",
        cargo_capacity_tracking: "optional",
      })
    );
    expect(result).toEqual({ volumeM3: 12, weightKg: 1500, hazmatCertifiedClasses: ["Sinif 8"] });
  });
});
